-- q93. which products are high-revenue but low-margin?

select
p.product_id,
p.product_name,
p.category,
round(sum(oi.sales_amount), 2) as revenue,
round(sum(oi.profit_amount), 2) as profit,
round(
sum(oi.profit_amount) / sum(oi.sales_amount) * 100,
2
) as profit_margin
from products p
join order_items oi
on p.product_id = oi.product_id
join orders o
on oi.order_id = o.order_id
where o.order_status != 'cancelled'
group by
p.product_id,
p.product_name,
p.category
having
sum(oi.sales_amount) > (
select avg(product_revenue)
from (
select
product_id,
sum(sales_amount) as product_revenue
from order_items
group by product_id
) as product_sales
)
and sum(oi.profit_amount) / sum(oi.sales_amount) < 0.20
order by revenue desc;

