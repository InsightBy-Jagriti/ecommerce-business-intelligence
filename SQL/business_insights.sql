-- q100. create an overall business performance classification

with category_performance as (
select
p.category,
sum(oi.sales_amount) as revenue,
sum(oi.profit_amount) as profit,
sum(oi.quantity) as units_sold
from products p
join order_items oi
on p.product_id = oi.product_id
join orders o
on oi.order_id = o.order_id
where o.order_status != 'cancelled'
group by p.category
),
category_analysis as (
select
category,
revenue,
profit,
units_sold,
profit / revenue * 100 as profit_margin
from category_performance
)
select
category,
round(revenue, 2) as revenue,
round(profit, 2) as profit,
units_sold,
round(profit_margin, 2) as profit_margin,
case
when profit_margin >= 30
and revenue >= (
select avg(revenue)
from category_analysis
)
then 'excellent'

    when profit_margin >= 20
         and revenue >= (
             select avg(revenue)
             from category_analysis
         )
        then 'strong'

    when profit_margin < 20
         and revenue >= (
             select avg(revenue)
             from category_analysis
         )
        then 'high sales - low margin'

    when profit_margin >= 20
         and revenue < (
             select avg(revenue)
             from category_analysis
         )
        then 'growth opportunity'
    else 'needs attention'
end as business_classification

from category_analysis
order by revenue desc;
